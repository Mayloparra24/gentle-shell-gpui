#!/usr/bin/env python3
"""Writes icon.svg: the Gentle Shell pixel rose on a dark plum squircle.

The rose is decoded from the braille art in crates/app/src/banner.rs, so the
icon and the in-app banner never drift apart. Layout follows Apple's macOS
icon template: a 1024 canvas with an 824 px continuous-corner body inset by
100 px (the margin leaves room for the baked-in drop shadow).

Standard library only; run through generate.sh, which also rasterizes.
"""

import math
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = pathlib.Path(__file__).resolve().parent / "icon.svg"

CANVAS = 1024
BODY = 824
INSET = (CANVAS - BODY) / 2
# Superellipse exponent approximating Apple's continuous corners (~22% radius).
SQUIRCLE_N = 4.6
PITCH = 9.6  # px per braille dot
DOT = 8.4  # painted dot side; the gap keeps the pixel-art texture

# Braille U+2800: bits 0-2 and 6 are the left column (rows 0-3), 3-5 and 7 the right.
DOTS = [(0, 0), (0, 1), (0, 2), (1, 0), (1, 1), (1, 2), (0, 3), (1, 3)]


def rose_dots():
    src = (ROOT / "crates/app/src/banner.rs").read_text(encoding="utf-8")
    block = re.search(r"const ROSE: &\[&str\] = &\[(.*?)\];", src, re.S)
    if block is None:
        raise SystemExit("ROSE art not found in banner.rs")
    dots = []
    for row, line in enumerate(re.findall(r'"(.*)"', block.group(1))):
        for col, ch in enumerate(line):
            bits = ord(ch) - 0x2800
            if not 0 <= bits <= 0xFF:
                continue
            for bit, (dx, dy) in enumerate(DOTS):
                if bits >> bit & 1:
                    dots.append((col * 2 + dx, row * 4 + dy))
    return dots


def squircle_path(half, dy=0.0):
    cx = CANVAS / 2
    cy = CANVAS / 2 + dy
    points = []
    steps = 720
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        x = cx + half * math.copysign(abs(c) ** (2 / SQUIRCLE_N), c)
        y = cy + half * math.copysign(abs(s) ** (2 / SQUIRCLE_N), s)
        points.append(f"{x:.2f},{y:.2f}")
    return "M" + " L".join(points) + " Z"


def main():
    dots = rose_dots()
    min_x = min(x for x, _ in dots)
    max_x = max(x for x, _ in dots)
    min_y = min(y for _, y in dots)
    max_y = max(y for _, y in dots)
    width = (max_x - min_x) * PITCH + DOT
    height = (max_y - min_y) * PITCH + DOT
    # Optically centred: a touch above the geometric middle.
    ox = (CANVAS - width) / 2 - min_x * PITCH
    oy = (CANVAS - height) / 2 - min_y * PITCH - 8
    top, bottom = oy + min_y * PITCH, oy + max_y * PITCH + DOT
    bloom_y = top + height * 0.3

    rects = "\n".join(
        f'    <rect x="{ox + x * PITCH:.1f}" y="{oy + y * PITCH:.1f}" '
        f'width="{DOT}" height="{DOT}" rx="1.6"/>'
        for x, y in sorted(dots, key=lambda d: (d[1], d[0]))
    )
    body = squircle_path(BODY / 2)
    # AppKit's SVG renderer ignores filters, so the drop shadow is a stack of
    # faint, progressively larger squircles instead of a Gaussian blur.
    shadow = "\n".join(
        f'    <path d="{squircle_path(BODY / 2 + k * 1.6, 3 + k * 1.8)}" fill-opacity="0.028"/>'
        for k in range(10)
    )
    svg = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by packaging/icons/generate.py from crates/app/src/banner.rs. Do not edit by hand. -->
<svg xmlns="http://www.w3.org/2000/svg" width="{CANVAS}" height="{CANVAS}" viewBox="0 0 {CANVAS} {CANVAS}">
  <defs>
    <linearGradient id="plum" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#1d0c19"/>
      <stop offset="0.55" stop-color="#0d060c"/>
      <stop offset="1" stop-color="#060407"/>
    </linearGradient>
    <radialGradient id="bloom" cx="512" cy="{bloom_y:.1f}" r="380" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#f095c8" stop-opacity="0.38"/>
      <stop offset="0.55" stop-color="#f095c8" stop-opacity="0.08"/>
      <stop offset="1" stop-color="#f095c8" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="sheen" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#ffffff" stop-opacity="0.10"/>
      <stop offset="0.45" stop-color="#ffffff" stop-opacity="0"/>
    </linearGradient>
    <linearGradient id="petal" x1="0" y1="{top:.1f}" x2="0" y2="{bottom:.1f}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#ffd0ea"/>
      <stop offset="0.35" stop-color="#f095c8"/>
      <stop offset="1" stop-color="#c8609c"/>
    </linearGradient>
    <clipPath id="body"><path d="{body}"/></clipPath>
  </defs>
  <g fill="#000000">
{shadow}
  </g>
  <g clip-path="url(#body)">
    <path d="{body}" fill="url(#plum)"/>
    <rect width="{CANVAS}" height="{CANVAS}" fill="url(#bloom)"/>
    <rect width="{CANVAS}" height="{CANVAS}" fill="url(#sheen)"/>
  </g>
  <g fill="url(#petal)">
{rects}
  </g>
</svg>
"""
    OUT.write_text(svg, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(dots)} dots)")


if __name__ == "__main__":
    main()
